val LocalLang = staticCompositionLocalOf { Lang.ES }

/** Texto traducido. Los argumentos sustituyen {0}, {1}… */
fun tr(lang: Lang, key: K, vararg args: Any): String {
    var s = catalog[lang]?.get(key) ?: ES[key] ?: key.name
    args.forEachIndexed { i, a -> s = s.replace("{$i}", a.toString()) }
    return s
}

@Composable
fun t(key: K, vararg args: Any): String = tr(LocalLang.current, key, *args)

fun nights(lang: Lang, n: Int): String = tr(lang, if (n == 1) K.NIGHTS_ONE else K.NIGHTS_OTHER, n)

